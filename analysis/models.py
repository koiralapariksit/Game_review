from django.db import models
from django.contrib.auth.models import User
from django.urls import reverse
from django.utils.text import slugify
from django.utils import timezone


class Article(models.Model):
    STATUS_DRAFT = 'DRAFT'
    STATUS_REVIEW_REQUIRED = 'REVIEW_REQUIRED'
    STATUS_APPROVED = 'APPROVED'
    STATUS_PUBLISHED = 'PUBLISHED'
    STATUS_ARCHIVED = 'ARCHIVED'

    STATUS_CHOICES = [
        (STATUS_DRAFT, 'Draft'),
        (STATUS_REVIEW_REQUIRED, 'Review Required'),
        (STATUS_APPROVED, 'Approved'),
        (STATUS_PUBLISHED, 'Published'),
        (STATUS_ARCHIVED, 'Archived'),
    ]

    CATEGORY_MATCH_REVIEW = 'MATCH_REVIEW'
    CATEGORY_TACTICAL_ANALYSIS = 'TACTICAL_ANALYSIS'
    CATEGORY_PLAYER_REPORT = 'PLAYER_REPORT'
    CATEGORY_TRANSFER_INTELLIGENCE = 'TRANSFER_INTELLIGENCE'
    CATEGORY_NEWS = 'NEWS'
    CATEGORY_OPINION = 'OPINION'

    CATEGORY_CHOICES = [
        (CATEGORY_MATCH_REVIEW, 'Match Review'),
        (CATEGORY_TACTICAL_ANALYSIS, 'Tactical Analysis'),
        (CATEGORY_PLAYER_REPORT, 'Player Report'),
        (CATEGORY_TRANSFER_INTELLIGENCE, 'Transfer Intelligence'),
        (CATEGORY_NEWS, 'News'),
        (CATEGORY_OPINION, 'Opinion'),
    ]

    title = models.CharField(max_length=200)
    slug = models.SlugField(unique=True, max_length=250)
    subtitle = models.CharField(max_length=255, blank=True, default='')
    content = models.TextField(help_text="Rich markdown article content")
    category = models.CharField(max_length=30, choices=CATEGORY_CHOICES, default=CATEGORY_MATCH_REVIEW)
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default=STATUS_DRAFT, db_index=True)
    match = models.ForeignKey(
        'matches.Match',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='analysis_articles'
    )
    player = models.ForeignKey(
        'players.Player',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='analysis_articles'
    )
    author = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='articles'
    )
    is_ai_generated = models.BooleanField(default=True)
    ai_disclosure = models.CharField(
        max_length=255,
        default="Generated by FCB AI Intelligence System with editorial verification"
    )
    image_url = models.URLField(max_length=500, blank=True, null=True, help_text="Optional external image URL")
    published_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(default=timezone.now)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-published_at', '-created_at']
        verbose_name = 'Article'
        verbose_name_plural = 'Articles'

    def __str__(self):
        return f"{self.title} [{self.get_status_display()}]"

    def get_absolute_url(self):
        return reverse('analysis:article_detail', kwargs={'slug': self.slug})

    @property
    def article_type(self):
        """Backward compatibility for templates/views referencing article_type"""
        if self.category == self.CATEGORY_TACTICAL_ANALYSIS:
            return 'tactical_analysis'
        return 'opinion'

    def save(self, *args, **kwargs):
        if not self.slug:
            base_slug = slugify(self.title) or "article"
            slug = base_slug
            counter = 1
            while Article.objects.filter(slug=slug).exclude(pk=self.pk).exists():
                slug = f"{base_slug}-{counter}"
                counter += 1
            self.slug = slug
        super().save(*args, **kwargs)

    def get_content_preview(self, words=30):
        """Return a preview of the content (first 30 words)"""
        return ' '.join(self.content.split()[:words]) + '...'


class ArticleRevision(models.Model):
    article = models.ForeignKey(
        Article,
        on_delete=models.CASCADE,
        related_name='revisions'
    )
    content_snapshot = models.TextField()
    edited_by = models.ForeignKey(
        User,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='article_revisions'
    )
    edit_summary = models.CharField(max_length=255, blank=True, default='')
    created_at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ['-created_at']
        verbose_name = 'Article Revision'
        verbose_name_plural = 'Article Revisions'

    def __str__(self):
        return f"Revision of {self.article.title} at {self.created_at.strftime('%Y-%m-%d %H:%M')}"


class AIWorkflowExecution(models.Model):
    STAGE_DETECTED = 'DETECTED'
    STAGE_DATA_COLLECTED = 'DATA_COLLECTED'
    STAGE_DATA_VALIDATED = 'DATA_VALIDATED'
    STAGE_ANALYZED = 'ANALYZED'
    STAGE_WRITTEN = 'WRITTEN'
    STAGE_FACT_CHECKED = 'FACT_CHECKED'
    STAGE_APPROVED = 'APPROVED'
    STAGE_PUBLISHED = 'PUBLISHED'
    STAGE_REVIEW_REQUIRED = 'REVIEW_REQUIRED'
    STAGE_FAILED = 'FAILED'

    STAGE_CHOICES = [
        (STAGE_DETECTED, 'Detected'),
        (STAGE_DATA_COLLECTED, 'Data Collected'),
        (STAGE_DATA_VALIDATED, 'Data Validated'),
        (STAGE_ANALYZED, 'Analyzed'),
        (STAGE_WRITTEN, 'Written'),
        (STAGE_FACT_CHECKED, 'Fact Checked'),
        (STAGE_APPROVED, 'Approved'),
        (STAGE_PUBLISHED, 'Published'),
        (STAGE_REVIEW_REQUIRED, 'Review Required'),
        (STAGE_FAILED, 'Failed'),
    ]

    match = models.ForeignKey(
        'matches.Match',
        on_delete=models.CASCADE,
        related_name='ai_executions'
    )
    stage = models.CharField(
        max_length=30,
        choices=STAGE_CHOICES,
        default=STAGE_DETECTED,
        db_index=True
    )
    model_identifier = models.CharField(max_length=120, blank=True, default='')
    prompt_tokens = models.PositiveIntegerField(default=0)
    completion_tokens = models.PositiveIntegerField(default=0)
    calculated_cost_usd = models.DecimalField(
        max_digits=6,
        decimal_places=5,
        default=0.0,
        help_text="Calculated cost in USD (0.00000 for free tier)"
    )
    validation_report = models.JSONField(null=True, blank=True)
    error_message = models.TextField(blank=True, default='')
    created_at = models.DateTimeField(default=timezone.now)
    completed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ['-created_at']
        verbose_name = 'AI Workflow Execution'
        verbose_name_plural = 'AI Workflow Executions'

    def __str__(self):
        return f"AI Execution #{self.id} for {self.match} [{self.get_stage_display()}]"
