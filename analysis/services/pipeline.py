import logging
from typing import Optional
from decimal import Decimal
from django.utils import timezone
from django.contrib.auth.models import User

from matches.models import Match
from analysis.models import Article, AIWorkflowExecution
from analysis.schemas import EditorialArticleSchema
from analysis.services.metrics import compute_match_metrics
from analysis.services.fact_checker import DeterministicFactChecker
from analysis.services.supervisor import EditorialSupervisorAgent
from analysis.services.ai_client import OpenRouterClient, AllFreeModelsUnavailableException

logger = logging.getLogger(__name__)


def run_match_intelligence_pipeline(
    match_id: int,
    article_data: Optional[EditorialArticleSchema] = None,
    auto_publish_mode: bool = True
) -> Article:
    """
    End-to-end autonomous match intelligence pipeline:
    1. Fetches match and computes deterministic metrics.
    2. Generates editorial match review via OpenRouter free model (if not provided).
    3. Runs DeterministicFactChecker (Score, Goalscorers, Stats).
       If invalid -> routes to REVIEW_REQUIRED.
    4. Runs EditorialSupervisorAgent (11 Sections Completeness, Anti-Repetition, Tone Filter).
       If rejected -> routes to REVIEW_REQUIRED with supervisor notes in validation_report.
    5. Publishes (Mode A) or queues for human approval (Mode B).
    """
    match = Match.objects.get(id=match_id)

    # 1. Initialize or load workflow execution
    execution = AIWorkflowExecution.objects.filter(match=match).order_by('-created_at').first()
    if not execution or execution.stage in [AIWorkflowExecution.STAGE_PUBLISHED, AIWorkflowExecution.STAGE_APPROVED]:
        execution = AIWorkflowExecution.objects.create(
            match=match,
            stage=AIWorkflowExecution.STAGE_DETECTED
        )

    # 2. Compute deterministic match metrics
    execution.stage = AIWorkflowExecution.STAGE_DATA_COLLECTED
    execution.save()
    match_metrics = compute_match_metrics(match.id)

    # 3. AI Generation if article_data not provided
    if article_data is None:
        execution.stage = AIWorkflowExecution.STAGE_ANALYZED
        execution.save()

        system_prompt = (
            "You are the Principal FC Barcelona Tactical Analyst and Chief Sports Journalist. "
            "Write a comprehensive, professional 11-section match review based strictly on the provided verified metrics. "
            "Never hallucinate goalscorers or contradict scorelines."
        )
        prompt = (
            f"Generate a full 11-section FC Barcelona match review for {match}:\n"
            f"Metrics: {match_metrics}\n"
        )

        ai_client = OpenRouterClient()
        try:
            article_data, telemetry = ai_client.generate_structured(
                prompt=prompt,
                system_prompt=system_prompt,
                schema_class=EditorialArticleSchema
            )
            execution.stage = AIWorkflowExecution.STAGE_WRITTEN
            execution.model_identifier = telemetry.get("model", "")
            execution.prompt_tokens = telemetry.get("prompt_tokens", 0)
            execution.completion_tokens = telemetry.get("completion_tokens", 0)
            execution.calculated_cost_usd = Decimal("0.00000")
            execution.save()
        except AllFreeModelsUnavailableException as exc:
            execution.stage = AIWorkflowExecution.STAGE_FAILED
            execution.error_message = f"AI Generation Failed: {exc}"
            execution.save()
            raise

    # 4. Gate 1: Deterministic Fact Checker
    fact_check_result = DeterministicFactChecker.verify_match_report(article_data, match)
    execution.stage = AIWorkflowExecution.STAGE_FACT_CHECKED

    if not fact_check_result.is_valid:
        execution.stage = AIWorkflowExecution.STAGE_REVIEW_REQUIRED
        execution.validation_report = {
            "fact_check": fact_check_result.model_dump(),
            "supervisor": None,
            "rejection_reason": "Fact Check Verification Failed",
            "fatal_errors": fact_check_result.fatal_errors,
        }
        execution.error_message = "; ".join(fact_check_result.fatal_errors)
        execution.save()

        article, _ = Article.objects.update_or_create(
            match=match,
            category=Article.CATEGORY_MATCH_REVIEW,
            defaults={
                'title': article_data.headline[:200],
                'subtitle': article_data.subtitle[:255],
                'content': article_data.markdown_body,
                'status': Article.STATUS_REVIEW_REQUIRED,
                'is_ai_generated': True,
                'ai_disclosure': 'Generated by FCB AI Intelligence System (Pending Editorial Review)',
            }
        )
        return article

    # 5. Gate 2: Editorial Quality Supervisor Agent
    existing_article = Article.objects.filter(match=match, category=Article.CATEGORY_MATCH_REVIEW).first()
    exclude_id = existing_article.id if existing_article else None

    supervisor_result = EditorialSupervisorAgent.evaluate_article(
        article_data=article_data,
        match=match,
        exclude_article_id=exclude_id
    )

    combined_validation = {
        "fact_check": fact_check_result.model_dump(),
        "supervisor": supervisor_result.model_dump(),
        "supervisor_notes": supervisor_result.supervisor_notes,
    }
    execution.validation_report = combined_validation

    if not supervisor_result.passed:
        execution.stage = AIWorkflowExecution.STAGE_REVIEW_REQUIRED
        execution.error_message = "; ".join(supervisor_result.supervisor_notes)
        execution.save()

        article, _ = Article.objects.update_or_create(
            match=match,
            category=Article.CATEGORY_MATCH_REVIEW,
            defaults={
                'title': article_data.headline[:200],
                'subtitle': article_data.subtitle[:255],
                'content': article_data.markdown_body,
                'status': Article.STATUS_REVIEW_REQUIRED,
                'is_ai_generated': True,
                'ai_disclosure': 'Generated by FCB AI Intelligence System (Supervisor Flagged for Review)',
            }
        )
        return article

    # 6. Both Gates Passed: Publish or Stage for Approval
    if auto_publish_mode:
        status = Article.STATUS_PUBLISHED
        published_at = timezone.now()
        execution.stage = AIWorkflowExecution.STAGE_PUBLISHED
    else:
        status = Article.STATUS_APPROVED
        published_at = None
        execution.stage = AIWorkflowExecution.STAGE_APPROVED

    execution.completed_at = timezone.now()
    execution.save()

    admin_author = User.objects.filter(is_superuser=True).first()

    article, _ = Article.objects.update_or_create(
        match=match,
        category=Article.CATEGORY_MATCH_REVIEW,
        defaults={
            'title': article_data.headline[:200],
            'subtitle': article_data.subtitle[:255],
            'content': article_data.markdown_body,
            'status': status,
            'published_at': published_at,
            'author': admin_author,
            'is_ai_generated': True,
            'ai_disclosure': 'Generated by FCB AI Intelligence System with editorial verification',
        }
    )
    return article

